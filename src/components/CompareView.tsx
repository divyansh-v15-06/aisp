import React from 'react';
import { Sparkles, Eye, Download, Copy, Check } from 'lucide-react';
import { JargonBusterResponse, ToneType } from '../types';
import { HighlightedText } from './HighlightedText';
import { AudioPlayer } from './AudioPlayer';

interface CompareViewProps {
  response: JargonBusterResponse;
  onSelectTone: (tone: ToneType) => void;
  onOpenGlossary: () => void;
}

export const CompareView: React.FC<CompareViewProps> = ({
  response,
  onSelectTone,
  onOpenGlossary,
}) => {
  const [copied, setCopied] = React.useState(false);

  const columns: {
    key: ToneType;
    label: string;
    icon: string;
    badgeColor: string;
    description: string;
  }[] = [
    {
      key: 'eli5',
      label: "Explain like I'm 5",
      icon: '🧸',
      badgeColor: 'text-indigo-600 dark:text-indigo-400 bg-indigo-50 dark:bg-indigo-950/60 border-indigo-200 dark:border-indigo-800',
      description: 'Everyday intuitive analogies & simple mental models',
    },
    {
      key: 'executive',
      label: 'Executive Summary',
      icon: '💼',
      badgeColor: 'text-emerald-600 dark:text-emerald-400 bg-emerald-50 dark:bg-emerald-950/60 border-emerald-200 dark:border-emerald-800',
      description: 'Architectural ROI, business value, velocity & trade-offs',
    },
    {
      key: 'technical',
      label: 'Deep Technical Breakdown',
      icon: '🔬',
      badgeColor: 'text-sky-600 dark:text-sky-400 bg-sky-50 dark:bg-sky-950/60 border-sky-200 dark:border-sky-800',
      description: 'Low-level protocols, internal state flows & invariants',
    },
  ];

  const handleCopyAll = () => {
    const text = `# Multi-Tone Technical Comparison: ${response.detectedDomain}\n\n` +
      `## 1. Explain Like I'm 5\n${response.explanations.eli5.coreExplanation}\n\n` +
      `## 2. Executive Summary\n${response.explanations.executive.coreExplanation}\n\n` +
      `## 3. Deep Technical Breakdown\n${response.explanations.technical.coreExplanation}\n\n` +
      `---\n*Generated by AI Jargon Buster*`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="flex flex-col h-full rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 shadow-xs overflow-hidden">
      {/* Header */}
      <div className="p-4 sm:p-5 border-b border-slate-200 dark:border-slate-800 bg-slate-50/50 dark:bg-slate-900/50 flex flex-wrap items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="text-[11px] font-mono uppercase tracking-wider text-slate-500 dark:text-slate-400 font-semibold px-2 py-0.5 rounded-md bg-slate-100 dark:bg-slate-800 border border-slate-200 dark:border-slate-700">
              {response.detectedDomain}
            </span>
            <span className="text-xs text-indigo-600 dark:text-indigo-400 font-semibold">
              Side-by-Side Tri-Tone Comparison
            </span>
          </div>
          <p className="text-xs text-slate-500 dark:text-slate-400">
            {response.originalSummary}
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleCopyAll}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-200 hover:bg-slate-100 dark:hover:bg-slate-700 transition-colors text-xs font-medium"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-500" /> : <Copy className="w-3.5 h-3.5" />}
            <span>Copy All Tones</span>
          </button>
        </div>
      </div>

      {/* 3-Column Comparative Grid */}
      <div className="flex-1 grid grid-cols-1 lg:grid-cols-3 divide-y lg:divide-y-0 lg:divide-x divide-slate-200 dark:divide-slate-800 overflow-y-auto">
        {columns.map(({ key, label, icon, badgeColor, description }) => {
          const exp = response.explanations[key];
          return (
            <div key={key} className="flex flex-col p-4 sm:p-5 space-y-4">
              {/* Column Header */}
              <div className="space-y-1.5">
                <div className="flex items-center justify-between">
                  <span className={`text-[11px] font-mono uppercase tracking-wider font-semibold px-2 py-0.5 rounded-md border ${badgeColor}`}>
                    {icon} {label}
                  </span>
                  <button
                    onClick={() => onSelectTone(key)}
                    className="text-[11px] text-slate-500 hover:text-indigo-600 dark:hover:text-indigo-400 flex items-center gap-1 font-medium transition-colors"
                  >
                    <Eye className="w-3 h-3" />
                    <span>Focus View</span>
                  </button>
                </div>
                <h3 className="text-sm sm:text-base font-bold text-slate-900 dark:text-white leading-snug">
                  {exp.title}
                </h3>
                <p className="text-[11px] text-slate-500 dark:text-slate-400">
                  {description}
                </p>
              </div>

              {/* Audio widget */}
              <AudioPlayer
                textToSpeak={exp.coreExplanation}
                title={exp.title}
                toneName={label}
              />

              {/* Core Text with highlights */}
              <div className="flex-1 text-xs sm:text-sm">
                <HighlightedText
                  text={exp.coreExplanation}
                  terms={exp.jargonTerms}
                />
              </div>

              {/* Persona specific insight */}
              {key === 'eli5' && exp.analogy && (
                <div className="p-3 rounded-lg bg-amber-50 dark:bg-amber-950/30 border border-amber-200/60 dark:border-amber-800/40 text-xs text-amber-900 dark:text-amber-200 italic">
                  💡 "{exp.analogy}"
                </div>
              )}

              {key === 'executive' && exp.businessImpact && (
                <div className="p-3 rounded-lg bg-emerald-50 dark:bg-emerald-950/30 border border-emerald-200/60 dark:border-emerald-800/40 text-xs text-emerald-900 dark:text-emerald-200">
                  📊 {exp.businessImpact}
                </div>
              )}

              {key === 'technical' && exp.architectureMechanics && (
                <div className="p-3 rounded-lg bg-sky-50 dark:bg-sky-950/30 border border-sky-200/60 dark:border-sky-800/40 text-xs text-sky-900 dark:text-sky-200 font-mono">
                  ⚙️ {exp.architectureMechanics}
                </div>
              )}

              {/* Takeaways */}
              <div className="pt-2 border-t border-slate-100 dark:border-slate-800 space-y-1.5 text-xs text-slate-700 dark:text-slate-300">
                <div className="text-[10px] font-mono uppercase tracking-wider text-slate-400 font-semibold">
                  Takeaways
                </div>
                <ul className="space-y-1">
                  {exp.keyTakeaways.map((item, i) => (
                    <li key={i} className="flex items-start gap-1.5">
                      <span className="text-indigo-500 font-bold">·</span>
                      <span className="leading-snug">{item}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
